// The one-off `Transactions` dashboard: a single spilling formula over the raw_* / ref_* sheets.
import { BadArgsError } from "../errors.ts";
import { colIndex, colLetter, ACCOUNTS, CATEGORIES, PROJECTS, TRANSACTIONS, type TableDef } from "./tables.ts";
import { quoteSheet, type SheetsSink } from "./sheets.ts";

export const DASHBOARD_HEADERS = ["Date", "Category", "Project", "Description", "Amount", "Account"] as const;
export const DASHBOARD_ROWS = 30_000; // the formula spills down; the grid must be tall enough
export const DASHBOARD_NOTE = "Generated by wps sheets init-dashboard; edit freely. Data comes from raw_* sheets.";

/** Open-ended data range of one column (row 2 down), letters derived from the table's column list. */
const colRange = (def: TableDef, key: string): string => {
  const L = colLetter(colIndex(def, key));
  return `${quoteSheet(def.sheet)}!${L}2:${L}`;
};

/** ARRAYFORMULA(IFERROR(VLOOKUP(...))) mapping `from` column values through a ref table's key -> value columns. */
function lookup(fromRange: string, ref: TableDef, keyCol: string, valCol: string): string {
  const k = colIndex(ref, keyCol);
  const v = colIndex(ref, valCol);
  if (v < k) throw new Error(`${ref.sheet}: '${valCol}' must be to the right of '${keyCol}' for VLOOKUP`);
  const table = `${quoteSheet(ref.sheet)}!${colLetter(k)}2:${colLetter(v)}`;
  return `ARRAYFORMULA(IFERROR(VLOOKUP(${fromRange}, ${table}, ${v - k + 1}, FALSE), ""))`;
}

export interface Layout { tx: TableDef; categories: TableDef; projects: TableDef; accounts: TableDef }
export const DEFAULT_LAYOUT: Layout = { tx: TRANSACTIONS, categories: CATEGORIES, projects: PROJECTS, accounts: ACCOUNTS };

export function transactionsFormula(layout: Layout = DEFAULT_LAYOUT): string {
  const t = (key: string) => colRange(layout.tx, key);
  const description = `ARRAYFORMULA(IF(${t("notes")}<>"", ${t("notes")}, ${t("shortDescription")}))`;
  const cols = [
    t("bookingDate"),
    lookup(t("categoryId"), layout.categories, "categoryId", "name"),
    lookup(t("projectId"), layout.projects, "id", "name"),
    description,
    t("amount"),
    lookup(t("accountId"), layout.accounts, "id", "name"),
  ];
  return `=IFERROR(SORT(FILTER({${cols.join(", ")}}, ${t("id")}<>"", ${t("deleted")}<>TRUE), 1, FALSE), "")`;
}

export interface InitResult { sheet: string; created?: true; renamed?: true; reused?: true }

export async function initDashboard(sink: SheetsSink, name: string, force: boolean, warn: (m: string) => void): Promise<InitResult> {
  let sheets = await sink.listSheets();
  for (const need of [TRANSACTIONS, CATEGORIES, PROJECTS, ACCOUNTS]) {
    if (!sheets.some((s) => s.title === need.sheet)) warn(`sheet '${need.sheet}' does not exist yet; run 'wps sheets sync --backfill' to fill the dashboard`);
  }
  const existing = sheets.find((s) => s.title === name);
  const result: InitResult = { sheet: name };
  if (existing) {
    const vals = await sink.readValues(name);
    const nonEmpty = vals.some((r) => r.some((c) => c !== "" && c !== null && c !== undefined));
    if (nonEmpty && !force) throw new BadArgsError(`sheet '${name}' already has content; use --force to overwrite it`);
    if (nonEmpty) await sink.clearValues(quoteSheet(name));
    result.reused = true;
  } else {
    const def = sheets.find((s) => s.title === "Sheet1");
    let renameOk = false;
    if (def) {
      const vals = await sink.readValues("Sheet1");
      renameOk = !vals.some((r) => r.some((c) => c !== "" && c !== null && c !== undefined));
    }
    if (def && renameOk) {
      await sink.batchUpdate([{ updateSheetProperties: { properties: { sheetId: def.sheetId, title: name }, fields: "title" } }]);
      result.renamed = true;
    } else {
      await sink.batchUpdate([{ addSheet: { properties: { title: name, gridProperties: { rowCount: DASHBOARD_ROWS, columnCount: DASHBOARD_HEADERS.length } } } }]);
      result.created = true;
    }
    sheets = await sink.listSheets();
  }
  const sheet = (await sink.listSheets()).find((s) => s.title === name)!;

  await sink.writeValues(`${quoteSheet(name)}!A1`, [["Transactions", DASHBOARD_NOTE], [], [...DASHBOARD_HEADERS]], "RAW");
  await sink.writeValues(`${quoteSheet(name)}!A4`, [[transactionsFormula()]], "USER_ENTERED"); // our own formula

  const id = sheet.sheetId;
  const fmt = (col: number, numberFormat: unknown) => ({
    repeatCell: {
      range: { sheetId: id, startRowIndex: 3, startColumnIndex: col, endColumnIndex: col + 1 },
      cell: { userEnteredFormat: { numberFormat } },
      fields: "userEnteredFormat.numberFormat",
    },
  });
  const bold = (row: number, size?: number) => ({
    repeatCell: {
      range: { sheetId: id, startRowIndex: row, endRowIndex: row + 1, startColumnIndex: 0, endColumnIndex: size ? 1 : DASHBOARD_HEADERS.length },
      cell: { userEnteredFormat: { textFormat: { bold: true, ...(size ? { fontSize: size } : {}) } } },
      fields: "userEnteredFormat.textFormat",
    },
  });
  await sink.batchUpdate([
    {
      updateSheetProperties: {
        properties: { sheetId: id, gridProperties: { rowCount: Math.max(sheet.rowCount, DASHBOARD_ROWS), frozenRowCount: 3 } },
        fields: "gridProperties.rowCount,gridProperties.frozenRowCount",
      },
    },
    bold(0, 14),
    bold(2),
    fmt(DASHBOARD_HEADERS.indexOf("Date"), { type: "DATE", pattern: "yyyy-mm-dd" }),
    fmt(DASHBOARD_HEADERS.indexOf("Amount"), { type: "NUMBER", pattern: "#,##0.00;[Red]-#,##0.00" }),
  ]);
  return result;
}
